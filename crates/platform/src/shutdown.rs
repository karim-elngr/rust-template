//! Portable process shutdown signals.

/// Wait for Ctrl-C or, on Unix, SIGTERM. Install this future early in process
/// startup; callers use its completion to stop admission and drain their tasks.
pub async fn signal() -> std::io::Result<()> {
    #[cfg(unix)]
    {
        let mut terminate =
            tokio::signal::unix::signal(tokio::signal::unix::SignalKind::terminate())?;
        tokio::select! {
            result = tokio::signal::ctrl_c() => result,
            _ = terminate.recv() => Ok(()),
        }
    }
    #[cfg(not(unix))]
    {
        tokio::signal::ctrl_c().await
    }
}
